const DICTIONARIES: Record<Lang, Record<MessageKey, string>> = { de, en };

function detect(): Lang {
  const saved = storage.get<Lang | null>('lang', null);
  if (saved === 'de' || saved === 'en') return saved;
  const preferred = navigator.languages?.length ? navigator.languages : [navigator.language];
  return preferred.find(l => /^(de|en)\b/i.test(l))?.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export const lang: Lang = detect();
export const locale = lang === 'de' ? 'de-DE' : 'en-GB';
document.documentElement.lang = lang;

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return DICTIONARIES[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

// Mehrzahl: tn('queue.waiting', n) nimmt bei n !== 1 den Schlüssel mit "Many"
export function tn(key: 'queue.waiting' | 'queue.failed', n: number): string {
  return t(n === 1 ? key : (`${key}Many` as MessageKey), { n });
}

export const reasonLabel = (reason: ReportReason) => t(`reason.${reason}`);

// Fehlermeldung vom Server in der eigenen Sprache (Code bekannt), sonst der Servertext
export function errorMessage(code: string | undefined, fallback: string): string {
  return code && `error.${code}` in de ? t(`error.${code}` as `error.${ErrorCode}`) : fallback;
}

export function setLang(next: Lang): void {
  storage.set('lang', next);
  location.reload();
}
